/**
 * Outlines the "Shaheen Money" wordmark into SVG path data.
 *
 *   node scripts/brand/build-wordmark.mjs
 *
 * The wordmark used to be live text, which meant it was drawn in Instrument
 * Sans on English pages and in whatever face the Arabic pages had loaded on
 * Arabic ones: the same logo in two different letterforms. Outlined once
 * from Instrument Sans Bold (the face the English lockup has always used),
 * it is identical in both languages and costs no font file at all.
 *
 * Writes src/assets/brand/wordmark.ts. Shaped with HarfBuzz, so kerning and
 * the -0.01em tracking of the old lockup are kept.
 */
import { readFile, writeFile } from 'node:fs/promises';
import * as hb from 'harfbuzzjs';
import wawoff2 from 'wawoff2';

const root = new URL('../../', import.meta.url);
const woff2 = await readFile(
  new URL('node_modules/@fontsource-variable/instrument-sans/files/instrument-sans-latin-wght-normal.woff2', root),
);
const ttf = await wawoff2.decompress(woff2);

const face = new hb.Face(new hb.Blob(ttf));
const font = new hb.Font(face);
font.setVariations([new hb.Variation('wght', 700)]);
const upem = face.upem;
const tracking = -0.01 * upem;

const text = 'Shaheen Money';
const buffer = new hb.Buffer();
buffer.addText(text);
buffer.guessSegmentProperties();
hb.shape(font, buffer);

const infos = buffer.getGlyphInfos();
const positions = buffer.getGlyphPositions();

/** Re-emits a HarfBuzz path with every coordinate moved into place (y flipped). */
function place(path, dx) {
  return path.replace(/([MLQCZ])([^MLQCZ]*)/g, (_, cmd, args) => {
    const nums = args.trim() ? args.trim().split(/[\s,]+/).map(Number) : [];
    const out = [];
    for (let i = 0; i < nums.length; i += 2) out.push(`${Math.round((nums[i] + dx) * 10) / 10} ${Math.round(-nums[i + 1] * 10) / 10}`);
    return cmd + out.join(' ');
  });
}

const words = { shaheen: '', money: '' };
let pen = 0;
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
infos.forEach((info, i) => {
  const pos = positions[i];
  const cluster = info.cluster;
  const path = font.glyphToPath(info.codepoint);
  if (path) {
    const placed = place(path, pen + pos.xOffset);
    if (cluster < 7) words.shaheen += placed;
    else words.money += placed;
    for (const m of placed.matchAll(/(-?\d+(?:\.\d+)?) (-?\d+(?:\.\d+)?)/g)) {
      const x = Number(m[1]);
      const y = Number(m[2]);
      minX = Math.min(minX, x);
      maxX = Math.max(maxX, x);
      minY = Math.min(minY, y);
      maxY = Math.max(maxY, y);
    }
  }
  pen += pos.xAdvance + tracking;
});

// The box is the ascender-to-descender band of the face, not the ink, so the
// wordmark sits on the same baseline and optical centre the text did.
const extents = font.hExtents();
const top = -extents.ascender;
const height = extents.ascender - extents.descender;
const x0 = Math.floor(minX) - 2;
const width = Math.ceil(maxX) + 2 - x0;

const ts = `/* GENERATED by scripts/brand/build-wordmark.mjs from Instrument Sans Bold. Do not edit. */

/** "Shaheen Money", outlined. Both words share one coordinate system (font units). */
export const wordmark = {
  viewBox: '${x0} ${Math.round(top)} ${width} ${Math.round(height)}',
  /** Width over height of the box: sets the rendered width from its height. */
  aspect: ${(width / height).toFixed(4)},
  /** Box height as a multiple of the font size the lockup was set at. */
  em: ${(height / upem).toFixed(4)},
  shaheen: '${words.shaheen}',
  money: '${words.money}',
} as const;
`;
await writeFile(new URL('src/assets/brand/wordmark.ts', root), ts);
console.log(`wordmark: ${width}x${Math.round(height)} font units (${(ts.length / 1024).toFixed(1)} KB), ink y ${minY}..${maxY}`);
